USE DATABASE CLOUDOPS_DB;

-- =====================================================
-- ROLE 1 : RAW READ-WRITE
-- =====================================================

CREATE ROLE IF NOT EXISTS CLOUDOPS_DB_RAW_RW
COMMENT = 'Read Write access on RAW schema';

GRANT USAGE ON DATABASE CLOUDOPS_DB
TO ROLE CLOUDOPS_DB_RAW_RW;

GRANT USAGE ON SCHEMA CLOUDOPS_DB.RAW
TO ROLE CLOUDOPS_DB_RAW_RW;

GRANT SELECT, INSERT, UPDATE, DELETE
ON ALL TABLES IN SCHEMA CLOUDOPS_DB.RAW
TO ROLE CLOUDOPS_DB_RAW_RW;

GRANT SELECT, INSERT, UPDATE, DELETE
ON FUTURE TABLES IN SCHEMA CLOUDOPS_DB.RAW
TO ROLE CLOUDOPS_DB_RAW_RW;

